"""Session 12: tables for the orientation-weakening dissection and the postsynaptic rollback.

Run from the repo root after scripts/run_session12.sh:
    .venv/bin/python scripts/summarize_session12.py
V1->V1, Nsyn model, slope per 10°. Writes notebooks/12_results_tables.md with:
  A. history per presynaptic cell type (4P, 23P): slope, shift from complete [95% paired bootstrap], gap beyond
     the distance-matched shuffle (p);
  B. count-matched random loss (histsub) vs the real history: does random within-axon loss of the same number of
     synapses per axon reproduce the history's slopes?
  C. pre + postsynaptic rollback (histpp) vs presynaptic-only rollback (hist): slope, shift [bootstrap], gaps.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from config import VERSION  # noqa: E402

TD = ROOT / "data" / "truncation"
PROJ = "V1->V1"
SIMS = {"rf_dist_deg": "RF", "ori_diff_deg": "orientation"}
STATES = {202304: "Apr 2023", 202511: "Nov 2025", 202602: "Feb 2026"}


def read(name):
    f = TD / name
    if not f.exists():
        return None
    d = pd.read_csv(f)
    d = d[(d["proj"] == PROJ) & (d["model"] == "Nsyn")].copy()
    d["level"] = d["level"].round(2)
    return d


def gap(real, perm, level, sim):
    if perm is None:
        return ""
    v = perm[(perm["level"] == round(level, 2)) & (perm["sim"] == sim)]["slope"].dropna().to_numpy()
    if not len(v):
        return ""
    mu = v.mean()
    p = (1 + np.sum(np.abs(v - mu) >= abs(real - mu))) / (1 + len(v))
    return f"{real - mu:+.3f} (p = {p:.3f})"


def boot_ci(boot, set_name, sim):
    if boot is None:
        return ""
    b0 = boot[boot["set"] == "radial_1.00_0"].set_index(["boot", "sim"])["slope"]
    b = boot[(boot["set"] == set_name) & (boot["sim"] == sim)]
    sh = b["slope"].to_numpy() - b0.reindex(list(zip(b["boot"], b["sim"]))).to_numpy()
    sh = sh[~np.isnan(sh)]
    if not len(sh):
        return ""
    q = np.quantile(sh, [.025, .975])
    return f"[{q[0]:+.3f}, {q[1]:+.3f}]"


def history_table(slopes, boot, perm_dist, perm_cell, prefix, ref_perm_dist=None, ref_perm_cell=None):
    full = slopes[slopes["set"] == "radial_1.00_0"].set_index("sim")["slope"]
    rows = []
    for sim, sl in SIMS.items():
        rows.append({"similarity": sl, "state": "complete", "slope": f"{full[sim]:+.3f}", "shift": "",
                     "beyond distance-matched shuffle": gap(full[sim], ref_perm_dist, 1.0, sim),
                     "beyond cell-type shuffle": gap(full[sim], ref_perm_cell, 1.0, sim)})
        for v, lab in STATES.items():
            r = slopes[(slopes["set"] == f"{prefix}_{v}_0") & (slopes["sim"] == sim)]
            if not len(r):
                continue
            s = r["slope"].iloc[0]
            rows.append({"similarity": sl, "state": lab, "slope": f"{s:+.3f}",
                         "shift": f"{s - full[sim]:+.3f} {boot_ci(boot, f'{prefix}_{v}_0', sim)}",
                         "beyond distance-matched shuffle": gap(s, perm_dist, float(v), sim),
                         "beyond cell-type shuffle": gap(s, perm_cell, float(v), sim)})
    return pd.DataFrame(rows)


def main():
    lines = [f"# Session 12 tables (auto-generated by scripts/summarize_session12.py, v{VERSION})\n",
             f"{PROJ}, Nsyn model, slope per 10°. Shift = slope(state) − slope(complete) [95% paired bootstrap over "
             "presynaptic neurons]. Beyond … shuffle = real − shuffled mean (p, two-sided, 200 shuffles).\n"]

    lines.append("## A. Real history by presynaptic cell type\n")
    for ct in ("4P", "23P"):
        sl = read(f"trunc_slopes_poisson_hist_{ct}.csv")
        if sl is None:
            lines.append(f"{ct}: not run\n")
            continue
        t = history_table(sl, read(f"trunc_boot_poisson_hist_{ct}.csv"), read(f"trunc_perm_poisson_hist_{ct}_nulldistance.csv"),
                          None, "hist", read(f"trunc_perm_poisson_{ct}_nulldistance.csv"))
        lines += [f"### {ct} axons\n", t.drop(columns="beyond cell-type shuffle").to_markdown(index=False), ""]

    lines.append("## B. Count-matched random loss vs the real history\n")
    sub, hist = read("trunc_slopes_poisson_histsub.csv"), read("trunc_slopes_poisson_hist.csv")
    if sub is None or hist is None:
        lines.append("not run\n")
    else:
        full = hist[hist["set"] == "radial_1.00_0"].set_index("sim")["slope"]
        rows = []
        for sim, lab in SIMS.items():
            for v in (202511, 202602):
                x = sub[(sub["cond"] == "histsub") & (sub["level"] == v) & (sub["sim"] == sim)]["slope"].dropna().to_numpy()
                real = hist[(hist["set"] == f"hist_{v}_0") & (hist["sim"] == sim)]["slope"].iloc[0]
                q = np.quantile(x, [.025, .975])
                rows.append({"similarity": lab, "state": STATES[v], "complete": f"{full[sim]:+.3f}",
                             "real history": f"{real:+.3f}",
                             "random loss, same count per axon: mean [2.5%, 97.5%]": f"{x.mean():+.3f} [{q[0]:+.3f}, {q[1]:+.3f}]",
                             "reps": len(x), "real within random range": "yes" if q[0] <= real <= q[1] else "no"})
        lines += ["Each complete axon keeps a random subset of its synapses of the size it had attached at that state "
                  "(Ld complete). Same per-axon counts as the history; random within each axon.\n",
                  pd.DataFrame(rows).to_markdown(index=False), ""]

    lines.append("## C. Pre- and postsynaptic rollback vs presynaptic only\n")
    pp = read("trunc_slopes_poisson_histpp.csv")
    if pp is None:
        lines.append("not run\n")
    else:
        t_pp = history_table(pp, read("trunc_boot_poisson_histpp.csv"), read("trunc_perm_poisson_histpp_nulldistance.csv"),
                             read("trunc_perm_poisson_histpp.csv"), "histpp",
                             read("trunc_perm_poisson_nulldistance.csv"), read("trunc_perm_poisson.csv"))
        t_h = history_table(hist, read("trunc_boot_poisson_hist.csv"), read("trunc_perm_poisson_hist_nulldistance.csv"),
                            read("trunc_perm_poisson_hist.csv"), "hist",
                            read("trunc_perm_poisson_nulldistance.csv"), read("trunc_perm_poisson.csv"))
        pp_md = ROOT / "notebooks" / "12_postsyn_history.md"
        if pp_md.exists():
            lines += [pp_md.read_text().split("\n", 2)[2], ""]
        lines += ["### Both sides rolled back\n", t_pp.to_markdown(index=False), "",
                  "### Presynaptic side only (Session 8, for comparison)\n", t_h.to_markdown(index=False), ""]
    (ROOT / "notebooks" / "12_results_tables.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
