"""Session 7: tables and figure for the truncation analysis.

Run from the repo root after scripts/like_to_like_trunc.R (fit; perm and boot are used if present):
    .venv/bin/python scripts/summarize_truncation.py

Writes notebooks/07_truncation_table.md and figures/07_truncation.png.

Uncertainty, in order of preference:
- the shift slope(f) - slope(1): paired bootstrap over presynaptic neurons (trunc_boot_*.csv),
  2.5-97.5 percentiles; otherwise not reported.
- the slope at each level: bootstrap percentiles if available, else Wald 95% CI (radial) and the
  range over reps (nulls).
- shuffled-wiring null at radial levels (trunc_perm_*.csv): mean and 2.5-97.5 percentiles, and the
  two-sided p centred on the null mean, as in Session 6.
"""
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from config import VERSION  # noqa: E402

TD = ROOT / "data" / "truncation"
MODEL_NAMES = {"Ld": "Ld (contact)", "Nsyn": "Nsyn (synapses)", "density": "Nsyn / Ld (synapses per contact)"}
SIM_NAMES = {"rf_dist_deg": "RF-centre distance", "ori_diff_deg": "orientation difference"}
COND = {  # validated categorical slots 1-3 (dataviz palette, light surface); markers as secondary encoding
    "radial": ("#2a78d6", "o", "-", "radial truncation"),
    "blocks": ("#eb6834", "s", "--", "random cable loss (null)"),
    "synsub": ("#1baf7a", "^", ":", "random synapse subsample (null)"),
}
INK, MUTED, GRID = "#1f1f1e", "#6b6a63", "#e4e3dd"


def read(name):
    fs = [TD / f"{name}_{t}.csv" for t in ("poisson", "tweedie")]
    fs = [f for f in fs if f.exists()]
    return pd.concat([pd.read_csv(f) for f in fs], ignore_index=True) if fs else None


def main():
    fit = read("trunc_slopes")
    fit["level"] = fit["level"].round(2)
    perm, boot = read("trunc_perm"), read("trunc_boot")
    ax_tab = pd.read_parquet(TD / f"trunc_axons_v{VERSION}.parquet")
    ax_tab["level"] = ax_tab["level"].astype(float).round(2)
    keep = ax_tab.groupby(["cond", "level", "rep"]).agg(syn=("n_syn_kept", "sum"), full=("n_syn_full", "sum"))
    syn_frac = (keep["syn"] / keep["full"]).groupby(["cond", "level"]).mean().rename("syn_frac")
    n_bad = (~fit["converged"].astype(bool)).sum()

    key = ["sim", "model", "proj"]
    full = fit[fit["set"] == "radial_1.00_0"].set_index(key)["slope"].rename("slope_full")
    agg = fit.groupby(key + ["cond", "level"]).agg(slope=("slope", "mean"), lo_rep=("slope", "min"),
                                                  hi_rep=("slope", "max"), SE=("SE", "mean"),
                                                  n_rep=("rep", "nunique")).reset_index()
    agg = agg.join(full, on=key)
    agg["shift"] = agg["slope"] - agg["slope_full"]
    agg = agg.join(syn_frac, on=["cond", "level"])

    if boot is not None:
        boot["level"] = boot["level"].round(2)
        b_full = boot[boot["set"] == "radial_1.00_0"].set_index(["boot"] + key)["slope"].rename("b_full")
        boot = boot.join(b_full, on=["boot"] + key)
        boot["b_shift"] = boot["slope"] - boot["b_full"]
        bq = boot.groupby(key + ["cond", "level"]).agg(
            boot_lo=("slope", lambda x: x.quantile(.025)), boot_hi=("slope", lambda x: x.quantile(.975)),
            shift_lo=("b_shift", lambda x: x.quantile(.025)), shift_hi=("b_shift", lambda x: x.quantile(.975)),
            n_boot=("boot", "nunique")).reset_index()
        agg = agg.merge(bq, on=key + ["cond", "level"], how="left")

    if perm is not None:
        perm["level"] = perm["level"].round(2)
        pq = perm.groupby(key + ["level"]).agg(
            null_mean=("slope", "mean"), null_lo=("slope", lambda x: x.quantile(.025)),
            null_hi=("slope", lambda x: x.quantile(.975)), n_perm=("perm", "nunique")).reset_index()
        agg = agg.merge(pq.assign(cond="radial"), on=key + ["cond", "level"], how="left")
        p_vals = []
        for _, r in agg[agg["cond"].eq("radial") & agg["null_mean"].notna()].iterrows():
            null = perm[(perm["sim"] == r["sim"]) & (perm["model"] == r["model"]) & (perm["proj"] == r["proj"])
                        & (perm["level"] == r["level"])]["slope"].dropna()
            m = null.mean()
            p_vals.append((r.name, (1 + (np.abs(null - m) >= abs(r["slope"] - m)).sum()) / (len(null) + 1)))
        agg.loc[[i for i, _ in p_vals], "p_vs_shuffle"] = [p for _, p in p_vals]

    # ------------------------------------------------------------ table
    lines = [f"# Truncation results (auto-generated by scripts/summarize_truncation.py, v{VERSION})\n",
             "Main-variant models (Session 6) refitted on each truncation set; 193 fully extended axons. "
             "Slopes per 10° on the log scale; negative = like-to-like. `level` = fraction of each axon's "
             "cable kept (synsub: synapses subsampled to the radial count at that level, cable complete). "
             "`syn_frac` = fraction of synapses onto usable neurons kept. Null rows are means over reps, "
             "with the rep range.\n",
             f"Non-converged fits: {n_bad} of {len(fit.groupby(['set'] + key[:2]))}.\n"]
    cols = ["cond", "level", "syn_frac", "slope", "shift"]
    for c in ("shift_lo", "shift_hi", "null_mean", "null_lo", "null_hi", "p_vs_shuffle", "n_perm"):
        if c in agg:
            cols.append(c)
    cols += ["SE", "lo_rep", "hi_rep"]
    for (sim, model, proj), g in agg.groupby(key, sort=False):
        g = g.sort_values(["cond", "level"], ascending=[True, False])
        lines += [f"## {SIM_NAMES[sim]}, {MODEL_NAMES[model]}, {proj}\n",
                  g[cols].to_markdown(index=False, floatfmt=".3f"), ""]
    (ROOT / "notebooks" / "07_truncation_table.md").write_text("\n".join(lines))

    # ------------------------------------------------------------ figure: V1->V1, 2 sims x 3 models
    plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                         "xtick.color": MUTED, "ytick.color": MUTED, "font.family": "DejaVu Sans"})
    models = [m for m in ("Ld", "Nsyn", "density") if m in set(agg["model"])]
    fig, axes = plt.subplots(2, len(models), figsize=(3.3 * len(models), 6.2), squeeze=False)
    for i, sim in enumerate(SIM_NAMES):
        for j, model in enumerate(models):
            ax = axes[i, j]
            g = agg[(agg["sim"] == sim) & (agg["model"] == model) & (agg["proj"] == "V1->V1")]
            if "null_mean" in g:
                n = g[g["cond"].eq("radial") & g["null_mean"].notna()].sort_values("level")
                if len(n):
                    ax.fill_between(n["level"], n["null_lo"], n["null_hi"], color="#c9c8c0", alpha=.5, lw=0,
                                    label="shuffled wiring, 95%", zorder=1)
                    ax.plot(n["level"], n["null_mean"], color="#9a998f", lw=1.2, zorder=2)
            ax.axhline(g["slope_full"].iloc[0], color=MUTED, lw=.8, ls=(0, (2, 2)), zorder=1)
            ax.axhline(0, color=GRID, lw=.8, zorder=0)
            for cond, (col, mk, ls, lab) in COND.items():
                c = g[g["cond"].isin([cond, "radial"]) if cond != "radial" else g["cond"].eq(cond)]
                c = pd.concat([c[c["cond"] == cond], c[(c["cond"] == "radial") & (c["level"] == 1)]])
                c = c.drop_duplicates("level").sort_values("level")
                if len(c) < 2:
                    continue
                if "boot_lo" in c and c["boot_lo"].notna().any():
                    lo, hi = c["boot_lo"], c["boot_hi"]
                elif cond == "radial":
                    lo, hi = c["slope"] - 1.96 * c["SE"], c["slope"] + 1.96 * c["SE"]
                else:
                    lo, hi = c["lo_rep"], c["hi_rep"]
                ax.fill_between(c["level"], lo, hi, color=col, alpha=.14, lw=0, zorder=2)
                ax.plot(c["level"], c["slope"], color=col, lw=2, ls=ls, marker=mk, ms=4.5, label=lab, zorder=3,
                        markeredgecolor="white", markeredgewidth=.6)
            ax.set_xlim(1.03, 0.27)
            ax.grid(axis="y", color=GRID, lw=.6)
            ax.spines[["top", "right"]].set_visible(False)
            if i == 0:
                ax.set_title(MODEL_NAMES[model], fontsize=9.5, color=INK)
            if i == 1:
                ax.set_xlabel("fraction of axon cable kept")
            if j == 0:
                ax.set_ylabel(f"{SIM_NAMES[sim]}\nslope per 10° (log scale)")
    h, lab = axes[0, 0].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=4, frameon=False, fontsize=8.5, bbox_to_anchor=(.5, -.01))
    band = "bootstrap 95%" if boot is not None else "Wald 95% (radial) / range over reps (nulls)"
    fig.suptitle("Like-to-like slope vs. simulated axon completeness, V1→V1", fontsize=10, color=INK, y=.995)
    fig.text(.5, .955, f"bands: {band}; dotted line: full axons", ha="center", fontsize=8, color=MUTED)
    fig.tight_layout(rect=(0, .05, 1, .95))
    out = ROOT / "figures" / "07_truncation.png"
    fig.savefig(out, dpi=200, facecolor="#fcfcfb")
    print(f"saved {out.relative_to(ROOT)}, notebooks/07_truncation_table.md; non-converged fits: {n_bad}")


if __name__ == "__main__":
    main()
