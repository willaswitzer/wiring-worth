"""Session 6: summary table and figure for the like-to-like models vs the shuffled-wiring control.

Run from the repo root after scripts/like_to_like.R (real fits + permutations):
    .venv/bin/python scripts/summarize_like_to_like.py

For every variant x similarity x model x projection type: real slope (log scale per 10 deg) with
its 95% Wald CI (emtrends), the shuffled mean and 2.5-97.5% interval, the number of converged
permutations, and a two-sided permutation p: (1 + #{|null - mean| >= |real - mean|}) / (N + 1).
Writes notebooks/06_like_to_like_table.md, data/like_to_like/summary.csv and
figures/06_like_to_like.png (main variant).
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
LTL = ROOT / "data" / "like_to_like"
TABLE_MD = ROOT / "notebooks" / "06_like_to_like_table.md"
FIG = ROOT / "figures" / "06_like_to_like.png"
SIM_LABEL = {"rf_dist_deg": "RF-centre distance", "ori_diff_deg": "Orientation difference"}
MODEL_LABEL = {"Ld": "Ld (Tweedie)", "Nsyn": "Nsyn (Poisson)", "density": "Nsyn / Ld (Poisson, offset)"}
MODEL_SHORT = {"Ld": "Ld", "Nsyn": "Nsyn", "density": "Nsyn/Ld"}
VARIANT_LABEL = {"main": "Main", "soma": "+ soma distance", "ext_dend": "Extended dendrites only"}
PROJ_ORDER = ["V1->V1", "V1->HVA (FF)", "HVA->HVA", "HVA->V1 (FB)"]
REAL, NULL_C, INK, MUTED, GRID, SURFACE = "#2a78d6", "#898781", "#0b0b0b", "#898781", "#e1e0d9", "#fcfcfb"
KEY = ["variant", "sim", "model", "proj"]


def load_perms():
    parts = []
    for f in sorted(LTL.glob("perm_slopes_*_*.csv")):
        variant = f.stem.replace("perm_slopes_", "").rsplit("_", 1)[0]
        parts.append(pd.read_csv(f).assign(variant=variant))
    perms = pd.concat(parts, ignore_index=True)
    perms["converged"] = perms["converged"].astype(str).str.upper().eq("TRUE")
    return perms


def summarize(real, perms):
    ok = perms[perms["converged"] & perms["slope"].notna()]
    rows = []
    for key, r in real.set_index(KEY).iterrows():
        null = ok.loc[(ok[KEY] == pd.Series(key, index=KEY)).all(axis=1), "slope"].to_numpy()
        n_run = perms.loc[(perms[KEY] == pd.Series(key, index=KEY)).all(axis=1), "perm"].nunique()
        mu = null.mean() if len(null) else np.nan
        p = (1 + np.sum(np.abs(null - mu) >= abs(r["slope"] - mu))) / (len(null) + 1) if len(null) else np.nan
        rows.append(dict(zip(KEY, key), slope=r["slope"], CI_low=r["CI_low"], CI_high=r["CI_high"],
                         p_wald=r["p_wald"], shuffle_mean=mu,
                         shuffle_lo=np.percentile(null, 2.5) if len(null) else np.nan,
                         shuffle_hi=np.percentile(null, 97.5) if len(null) else np.nan,
                         n_perm=len(null), n_perm_run=n_run, p_shuffle=p, n_pairs=r["n_pairs"],
                         real_converged=bool(r["converged"]) and bool(r["pdHess"])))
    return pd.DataFrame(rows)


def fmt_table(s):
    t = s.copy()
    t["similarity"] = t["sim"].map(SIM_LABEL)
    t["model"] = t["model"].map(MODEL_LABEL)
    t["real slope [95% CI]"] = t.apply(lambda r: f"{r.slope:+.3f} [{r.CI_low:+.3f}, {r.CI_high:+.3f}]", axis=1)
    t["shuffled mean [95% interval]"] = t.apply(
        lambda r: f"{r.shuffle_mean:+.3f} [{r.shuffle_lo:+.3f}, {r.shuffle_hi:+.3f}]", axis=1)
    t["p vs shuffle"] = t["p_shuffle"].map(lambda p: "n/a" if np.isnan(p) else f"{p:.3f}" if p >= 0.001 else "<0.001")
    t["n perms"] = t["n_perm"]
    return t[["model", "similarity", "proj", "real slope [95% CI]", "shuffled mean [95% interval]",
              "p vs shuffle", "n perms", "n_pairs"]]


def main():
    real = pd.read_csv(LTL / "real_slopes.csv")
    perms = load_perms()
    s = summarize(real, perms)
    s["proj"] = pd.Categorical(s["proj"], PROJ_ORDER, ordered=True)
    s = s.sort_values(["variant", "model", "sim", "proj"], key=lambda c: c.map(
        {"main": 0, "soma": 1, "ext_dend": 2, "Ld": 0, "Nsyn": 1, "density": 2, "rf_dist_deg": 0,
         "ori_diff_deg": 1}) if c.name in ("variant", "model", "sim") else c)
    s.to_csv(LTL / "summary.csv", index=False)

    incl = pd.read_csv(LTL / "inclusion.csv")
    lines = ["# Session 6 like-to-like table (auto-generated by scripts/summarize_like_to_like.py, v1822)\n",
             "Slopes are on the log (link) scale per 10 deg of dissimilarity (negative = like-to-like). "
             "Real CI = 95% Wald CI from emtrends. Shuffle = postsynaptic functional properties permuted "
             "within cell type x area; p = two-sided permutation p centred on the shuffled mean; "
             "n perms = converged permutations.\n"]
    for v in ["main", "soma", "ext_dend"]:
        lines += [f"## {VARIANT_LABEL[v]}\n", fmt_table(s[s["variant"] == v]).to_markdown(index=False), ""]
    conv = perms.groupby(["variant", "sim", "model"]).agg(run=("perm", "nunique"),
                                                          failed=("converged", lambda x: (~x).sum()))
    lines += ["## Permutation counts (run / non-converged fits)\n", conv.to_markdown(), "",
              "## Projection-type inclusion (> 30 synapses, > 5 presynaptic neurons, no neuron > 50%)\n",
              incl.to_markdown(index=False), ""]
    TABLE_MD.write_text("\n".join(lines))
    print("\n".join(lines[:8]))

    # %% Figure: main variant; rows = models, cols = similarity; real point + CI vs shuffled strip
    plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
                         "ytick.color": INK, "axes.spines.top": False, "axes.spines.right": False})
    ok = perms[perms["converged"] & (perms["variant"] == "main")]
    fig, axes = plt.subplots(3, 2, figsize=(10.5, 8), facecolor=SURFACE, constrained_layout=True)
    rng = np.random.default_rng(0)
    for i, model in enumerate(["Ld", "Nsyn", "density"]):
        for j, sim in enumerate(["rf_dist_deg", "ori_diff_deg"]):
            ax = axes[i, j]
            d = s[(s["variant"] == "main") & (s["model"] == model) & (s["sim"] == sim)]
            projs = [p for p in PROJ_ORDER if p in set(d["proj"].astype(str))]
            for k, proj in enumerate(projs):
                y = len(projs) - 1 - k
                null = ok.loc[(ok["model"] == model) & (ok["sim"] == sim) & (ok["proj"] == proj), "slope"]
                ax.scatter(null, y + rng.uniform(-0.18, 0.18, len(null)), s=4, color=NULL_C, alpha=0.35,
                           lw=0, label="shuffled" if k == 0 else None)
                r = d[d["proj"].astype(str) == proj].iloc[0]
                ax.plot([r.shuffle_lo, r.shuffle_hi], [y - 0.3, y - 0.3], color=NULL_C, lw=2,
                        solid_capstyle="round", label="shuffled 95% interval" if k == 0 else None)
                ax.errorbar(r.slope, y + 0.3, xerr=[[r.slope - r.CI_low], [r.CI_high - r.slope]], fmt="o",
                            color=REAL, ms=6, lw=2, capsize=0, label="real (95% CI)" if k == 0 else None)
                ax.annotate("p n/a" if np.isnan(r.p_shuffle) else f"p = {r.p_shuffle:.3f}",
                            (1.02, y), xycoords=("axes fraction", "data"), ha="left", va="center",
                            fontsize=8, color=INK, annotation_clip=False)
            ax.axvline(0, color=MUTED, lw=0.8)
            ax.set_yticks(range(len(projs)))
            ax.set_yticklabels(list(reversed(projs)))
            ax.set_ylim(-0.7, len(projs) - 0.3)
            ax.grid(axis="x", color=GRID, lw=0.6)
            ax.set_axisbelow(True)
            ax.set_facecolor(SURFACE)
            n = int(d["n_perm"].min()) if len(d) else 0
            ax.set_title(f"{MODEL_SHORT[model]} · {SIM_LABEL[sim]}   ({n} shuffles)", loc="left", fontsize=9.5,
                         color=INK)
            if i == 2:
                ax.set_xlabel("Slope, log scale per 10° dissimilarity (negative = like-to-like)")
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside upper center", ncol=3, frameon=False, fontsize=8.5)
    fig.savefig(FIG, dpi=160, facecolor=SURFACE)
    print(f"saved {FIG.relative_to(ROOT)}, {TABLE_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
