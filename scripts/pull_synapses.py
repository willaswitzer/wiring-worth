"""Session 3: synapses among the usable set.

Run from the repo root after scripts/build_usable_set.py:
    .venv/bin/python scripts/pull_synapses.py

Pre: usable neurons with a fully or partially extended axon. Post: any usable neuron.
Synapse table = the datastack's default (`synapses_pni_2` at v1822), positions in nm.
Autapses (pre == post) are kept in the file but excluded from pair counts.
"""
import sys
import warnings
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from config import DATASTACK, VERSION, VSFX  # noqa: E402
from caveclient import CAVEclient  # noqa: E402

DATA = ROOT / "data"
OUT = DATA / f"synapses_usable_v{VERSION}.parquet"
COUNTS_MD = ROOT / "notebooks" / f"03_synapse_counts{VSFX}.md"
PRE_AXON = ["axon_fully_extended", "axon_partially_extended"]
CHUNK = 25  # presynaptic roots per query

client = CAVEclient(DATASTACK, version=VERSION)
SYN = client.info.get_datastack_info()["synapse_table"]
usable = pd.read_parquet(DATA / f"usable_set_v{VERSION}_s2.parquet")
pre = usable[usable["axon_level"].isin(PRE_AXON)]
post_ids = usable["root_id"].tolist()
print(f"{SYN} @ v{VERSION}: {len(pre)} presynaptic neurons, {len(post_ids)} postsynaptic neurons")

# %% Query in chunks of presynaptic roots; fail loudly if a chunk could be truncated
parts = []
pre_ids = pre["root_id"].tolist()
for i in range(0, len(pre_ids), CHUNK):
    chunk = pre_ids[i:i + CHUNK]
    with warnings.catch_warnings(record=True) as w:
        warnings.simplefilter("always")
        df = client.materialize.query_table(
            SYN,
            filter_in_dict={"pre_pt_root_id": chunk, "post_pt_root_id": post_ids},
            select_columns=["id", "pre_pt_root_id", "post_pt_root_id", "size", "ctr_pt_position"],
            desired_resolution=[1, 1, 1],
            split_positions=True,
        )
    assert not any("Limited query" in str(x.message) for x in w), f"chunk {i} truncated"
    parts.append(df)
    print(f"  pre {i + len(chunk)}/{len(pre_ids)}: {len(df)} synapses")
syn = pd.concat(parts, ignore_index=True)
assert not syn["id"].duplicated().any()
assert syn["pre_pt_root_id"].isin(pre_ids).all() and syn["post_pt_root_id"].isin(post_ids).all()

syn = syn.rename(columns={"id": "synapse_id", "pre_pt_root_id": "pre_root_id", "post_pt_root_id": "post_root_id",
                          "ctr_pt_position_x": "ctr_x_nm", "ctr_pt_position_y": "ctr_y_nm",
                          "ctr_pt_position_z": "ctr_z_nm"})
syn = syn[["synapse_id", "pre_root_id", "post_root_id", "size", "ctr_x_nm", "ctr_y_nm", "ctr_z_nm"]]
syn.attrs.update(version=str(VERSION), synapse_table=SYN)
syn.to_parquet(OUT)
autapse = syn["pre_root_id"] == syn["post_root_id"]
print(f"saved {len(syn)} synapses ({autapse.sum()} autapses) -> {OUT.relative_to(ROOT)}")

# %% Connected pairs by presynaptic cell type x axon level
s = syn[~autapse]
pairs = s.groupby(["pre_root_id", "post_root_id"]).size().rename("n_syn").reset_index()
meta = pre.set_index("root_id")[["cell_type", "axon_level"]]
pairs = pairs.join(meta, on="pre_root_id")
s = s.join(meta, on="pre_root_id")
n_post = len(post_ids)

g = ["cell_type", "axon_level"]
tab = pd.DataFrame({
    "pre_neurons": pre.groupby(g).size(),
    "pre_with_output": pairs.groupby(g)["pre_root_id"].nunique(),
    "synapses": s.groupby(g).size(),
    "connected_pairs": pairs.groupby(g).size(),
}).fillna(0).astype(int)
tab["possible_pairs"] = tab["pre_neurons"] * (n_post - 1)
tab.loc[("**All**", ""), :] = tab.sum()
tab["p_connect"] = (tab["connected_pairs"] / tab["possible_pairs"]).round(4)
tab = tab.rename(index={"axon_fully_extended": "fully_ext", "axon_partially_extended": "partially_ext"})

wide = pairs.assign(axon=pairs["axon_level"].map({"axon_fully_extended": "fully_ext",
                                                  "axon_partially_extended": "partially_ext"}))
wide = pd.crosstab(wide["cell_type"], wide["axon"], margins=True, margins_name="All")

lines = [f"# Session 3 synapse counts (auto-generated by scripts/pull_synapses.py, v{VERSION})\n",
         f"`{SYN}`; pre = {len(pre)} usable neurons with fully/partially extended axons; "
         f"post = all {n_post} usable neurons. {len(syn):,} synapses, {autapse.sum()} autapses "
         f"(excluded below). possible_pairs = pre_neurons x {n_post - 1}.\n",
         "## Connected pairs, pre cell type x pre axon level\n", wide.to_markdown(), "",
         "## Detail\n", tab.to_markdown(), "",
         "## Synapses per connected pair\n", pairs["n_syn"].describe().to_frame().T.to_markdown(index=False), ""]
COUNTS_MD.write_text("\n".join(lines))
print("\n".join(lines))
